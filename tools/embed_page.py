#!/usr/bin/env python3
"""tools/embed_page.py - write build/rig_page.h: dist/rig-test.html as bytes, so rig-host serves its own page
(one file to download and run). Usage: embed_page.py [page] [out]"""
import pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'dist/rig-test.html'
out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / 'build/rig_page.h'
data = src.read_bytes()
lines = ['// GENERATED by tools/embed_page.py from %s. Do not edit.' % src.name, '#pragma once', '#include <cstddef>',
         'static const unsigned char RIG_PAGE[] = {']
for i in range(0, len(data), 40):
    lines.append(','.join(str(b) for b in data[i:i + 40]) + ',')
lines += ['};', 'static const size_t RIG_PAGE_LEN = %d;' % len(data), '']
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(lines))
print(f'   {out.relative_to(root)}: {len(data) // 1024} KB page')
