#!/usr/bin/env python3
"""tools/build_plugin.py - build a RIG/01 plugin folder into one .rigfx bundle.

    python3 tools/build_plugin.py plugins/trem            -> dist/plugins/trem.rigfx
    python3 tools/build_plugin.py plugins/trem -o out.rigfx

A plugin folder holds the effect or source header (<id>.h, written as a built-in one) and plugin.json:
    {"struct": "rig::Trem", "kind": "effect" | "source", "category": "modulation",
     "tags": ["tremolo", ...], "author": "...", "version": "1.0.0"}
and optionally screen.js (a face screen for the page, as ui/screens/<type>.js; effects only).

The bundle is a zip (stored, not compressed: the page reads it without a library) holding:
    manifest.json                    id, name, kind, category, tags, author, version, params, files, and the
                                     plugin's full description (what rig01.describe/1 returns)
    clap/x86_64-linux.clap           native CLAP for Linux (the rig-host loads it; any CLAP host can)
    clap/x86_64-windows.clap         native CLAP for Windows
    module.wclap                     WebCLAP: the same plugin as WebAssembly, for the browser
    screen.js                        if the folder has one
Everything is compiled with zig (pip package `ziglang`, as build.sh uses), so one machine builds all
three. The rig itself isn't rebuilt: the bundle is added from the library (docs/PLUGINS.md).
"""
import argparse, io, json, os, subprocess, sys, tempfile, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZIG = [sys.executable, '-m', 'ziglang']
INC = ['-I', os.path.join(ROOT, 'sdk'), '-I', os.path.join(ROOT, 'engine', 'core'),
       '-isystem', os.path.join(ROOT, 'third_party', 'clap', 'include')]
WARN = ['-std=c++20', '-Wall', '-Wextra', '-Werror', '-O2', '-fno-exceptions', '-fno-rtti']
TARGETS = {
    'clap/x86_64-linux.clap': ['-target', 'x86_64-linux-gnu', '-shared', '-fPIC', '-fvisibility=hidden', '-s'],
    'clap/x86_64-windows.clap': ['-target', 'x86_64-windows-gnu', '-shared', '-D_USE_MATH_DEFINES', '-s'],
    # A WebCLAP: a reactor module exporting clap_entry (the address of the entry struct), its memory,
    # its one function table (growable, so the host can add its callbacks) and malloc.
    'module.wclap': ['-target', 'wasm32-wasi', '-mexec-model=reactor', '-msimd128', '-s',
                     '-Wl,--export=clap_entry', '-Wl,--export=malloc', '-Wl,--export=free',
                     '-Wl,--export-table', '-Wl,--growable-table'],
}

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('folder'); ap.add_argument('-o', '--out')
    ap.add_argument('--if-stale', action='store_true', help='skip if the bundle is newer than everything it is built from')
    a = ap.parse_args()
    folder = os.path.abspath(a.folder)
    meta = json.load(open(os.path.join(folder, 'plugin.json')))
    pid = os.path.basename(folder.rstrip('/'))
    header = os.path.join(folder, pid + '.h')
    if not os.path.exists(header): sys.exit(f'{header}: missing (the plugin folder holds <id>.h)')
    kind = meta.get('kind', 'effect')
    if kind not in ('effect', 'source'): sys.exit('plugin.json: kind is "effect" or "source"')
    macro = 'RIGFX_SOURCE' if kind == 'source' else 'RIGFX_EFFECT'
    entry = (f'// generated by tools/build_plugin.py for {pid}\n#include "rigfx.h"\n#include {cstr(header)}\n'
             f'{macro}({meta["struct"]}, {cstr(meta.get("category", "experimental"))}, {cstr(json.dumps(meta.get("tags", [])))}, '
             f'{cstr(meta.get("author", ""))}, {cstr(meta.get("version", "1.0.0"))})\n')
    out = a.out or os.path.join(ROOT, 'dist', 'plugins', pid + '.rigfx')
    if a.if_stale and os.path.exists(out):
        srcs = [os.path.join(folder, f) for f in os.listdir(folder)] + [os.path.abspath(__file__)]
        for d in ('sdk', 'engine/core'): srcs += [os.path.join(ROOT, d, f) for f in os.listdir(os.path.join(ROOT, d))]
        if max(os.path.getmtime(f) for f in srcs) < os.path.getmtime(out):
            print(f'   {pid}: up to date ({os.path.relpath(out, ROOT)})'); return
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    env = dict(os.environ)
    env.setdefault('ZIG_GLOBAL_CACHE_DIR', os.path.join(ROOT, 'build', 'zig-cache'))
    env.setdefault('ZIG_LOCAL_CACHE_DIR', os.path.join(ROOT, 'build', 'zig-cache'))
    files = {}
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, 'entry.cpp'); open(src, 'w').write(entry)
        for name, flags in TARGETS.items():
            bin_ = os.path.join(tmp, name.replace('/', '_'))
            cmd = ZIG + ['c++'] + flags + WARN + INC + ['-o', bin_, src]
            r = subprocess.run(cmd, env=env, capture_output=True, text=True)
            if r.returncode: sys.exit(f'{name}: build failed\n{r.stderr}')
            files[name] = open(bin_, 'rb').read()
            print(f'   {pid}: {name} ({len(files[name]) // 1024} KB)')
    # The description the plugin gives the rig, read back from a native build (so the manifest can't
    # disagree with the code): build a tiny reader for this machine.
    desc = describe(entry, env)
    manifest = {'format': 'rigfx', 'version': 1, 'id': desc['id'], 'clapId': 'com.rig01.' + desc['id'], 'name': desc['name'],
                'sub': desc['sub'], 'kind': kind, 'category': desc['category'], 'tags': desc['tags'], 'author': desc['author'],
                'pluginVersion': desc['version'], 'params': [p['symbol'] for p in desc['params']], 'files': sorted(files),
                # the plugin's own description (sdk/rig_clap_ext.h), so the page can list it before it's loaded
                'description': desc}
    screen = os.path.join(folder, 'screen.js')
    if os.path.exists(screen): files['screen.js'] = open(screen, 'rb').read(); manifest['files'].append('screen.js')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', zipfile.ZIP_STORED) as z:
        z.writestr('manifest.json', json.dumps(manifest, indent=2))
        for name, data in sorted(files.items()): z.writestr(name, data)
    open(out, 'wb').write(buf.getvalue())
    print(f'   wrote {os.path.relpath(out, ROOT)} ({len(buf.getvalue()) // 1024} KB): {manifest["name"]} ({kind}, {manifest["category"]})')

def describe(entry, env):
    """Compile the plugin natively with a reader that prints its rig01.describe/1 JSON."""
    reader = entry + r'''
#include <cstdio>
int main() {
  clap_entry.init("");
  auto* f = (const clap_plugin_factory_t*)clap_entry.get_factory(CLAP_PLUGIN_FACTORY_ID);
  static clap_host_t host = {CLAP_VERSION_INIT, nullptr, "describe", "", "", "", nullptr, nullptr, nullptr, nullptr};
  host.get_extension = [](const clap_host_t*, const char*) -> const void* { return nullptr; };
  host.request_restart = [](const clap_host_t*) {}; host.request_process = [](const clap_host_t*) {}; host.request_callback = [](const clap_host_t*) {};
  const clap_plugin_t* p = f->create_plugin(f, &host, f->get_plugin_descriptor(f, 0)->id);
  p->init(p);
  auto* r = (const rig_plugin_describe_t*)p->get_extension(p, RIG_EXT_DESCRIBE);
  puts(r->json(p)); p->destroy(p); clap_entry.deinit(); return 0;
}
'''
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, 'reader.cpp'); open(src, 'w').write(reader)
        exe = os.path.join(tmp, 'reader')
        r = subprocess.run(['c++', '-std=c++20', '-O1', '-w'] + INC + ['-o', exe, src], capture_output=True, text=True)
        if r.returncode: sys.exit('reading the description failed\n' + r.stderr)
        return json.loads(subprocess.run([exe], capture_output=True, text=True, check=True).stdout)

if __name__ == '__main__':
    main()
